-- Homologação — paridade mínima do módulo Atas, Saldos e Pedidos.
-- Somente para o projeto de staging xnktywrdoqlacwmdemfp.
-- Não copia dados de produção e não deve ser aplicada no projeto principal.

CREATE TABLE public.itens_ata (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ata_id integer NOT NULL REFERENCES public.atas(id) ON DELETE CASCADE,
  tenant_id uuid NOT NULL REFERENCES public.app_tenants(id) ON DELETE CASCADE,
  unidade_id uuid REFERENCES public.app_tenant_units(id) ON DELETE SET NULL,
  item_numero text NOT NULL,
  descricao text NOT NULL,
  unidade_medida text NOT NULL DEFAULT 'UN',
  quantidade_contratada numeric NOT NULL CHECK (quantidade_contratada >= 0),
  valor_unitario numeric NOT NULL CHECK (valor_unitario >= 0),
  saldo_quantidade numeric NOT NULL CHECK (saldo_quantidade >= 0),
  saldo_valor numeric NOT NULL CHECK (saldo_valor >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, ata_id, item_numero)
);

CREATE TABLE public.pedidos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id uuid NOT NULL REFERENCES public.app_tenants(id) ON DELETE CASCADE,
  unidade_id uuid REFERENCES public.app_tenant_units(id) ON DELETE SET NULL,
  numero_pedido text NOT NULL,
  usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  ata_id integer NOT NULL REFERENCES public.atas(id) ON DELETE RESTRICT,
  orgao_solicitante_id integer,
  fornecedor_id integer,
  data_solicitacao date NOT NULL DEFAULT current_date,
  status text NOT NULL DEFAULT 'AGUARDANDO_APROVACAO',
  status_aprovacao text NOT NULL DEFAULT 'AGUARDANDO_APROVACAO',
  aprovado_por integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  data_aprovacao date,
  observacoes text,
  valor_total numeric NOT NULL DEFAULT 0 CHECK (valor_total >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, numero_pedido)
);

CREATE TABLE public.itens_pedido (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id uuid NOT NULL REFERENCES public.app_tenants(id) ON DELETE CASCADE,
  pedido_id integer NOT NULL REFERENCES public.pedidos(id) ON DELETE CASCADE,
  item_ata_id integer NOT NULL REFERENCES public.itens_ata(id) ON DELETE RESTRICT,
  quantidade_solicitada numeric NOT NULL CHECK (quantidade_solicitada > 0),
  valor_unitario numeric NOT NULL CHECK (valor_unitario >= 0),
  valor_total numeric NOT NULL CHECK (valor_total >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, pedido_id, item_ata_id)
);

CREATE TABLE public.consumos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id uuid NOT NULL REFERENCES public.app_tenants(id) ON DELETE CASCADE,
  unidade_id uuid REFERENCES public.app_tenant_units(id) ON DELETE SET NULL,
  usuario_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  ata_id integer NOT NULL REFERENCES public.atas(id) ON DELETE RESTRICT,
  item_ata_id integer NOT NULL REFERENCES public.itens_ata(id) ON DELETE RESTRICT,
  orgao_solicitante_id integer,
  quantidade numeric NOT NULL CHECK (quantidade > 0),
  valor_unitario numeric NOT NULL CHECK (valor_unitario >= 0),
  valor_total numeric NOT NULL CHECK (valor_total >= 0),
  data_consumo date NOT NULL DEFAULT current_date,
  observacao text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX itens_ata_tenant_item_idx ON public.itens_ata(tenant_id, id);
CREATE INDEX pedidos_tenant_status_idx ON public.pedidos(tenant_id, status_aprovacao, id);
CREATE INDEX itens_pedido_tenant_pedido_idx ON public.itens_pedido(tenant_id, pedido_id);
CREATE INDEX consumos_tenant_item_idx ON public.consumos(tenant_id, item_ata_id, id);

